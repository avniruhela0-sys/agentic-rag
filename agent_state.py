def validate_state(state: AgentState) -> List[str]:
    """
    Validate that the state has all required fields.
    
    Returns:
        List of missing fields (empty if valid)
    """
    required_fields = [
        "question", "sub_questions", "retrieved_docs",
        "draft_answer", "judge_score", "judge_feedback",
        "judge_issue", "correction_attempts", "correction_history",
        "final_answer", "sources", "start_time", "node_history"
    ]
    
    missing = []
    for field in required_fields:
        if field not in state:
            missing.append(field)
    
    return missing

