def update_state(state: AgentState, updates: Dict[str, Any]) -> AgentState:
    """
    Safely update state with new values.
    
    Args:
        state: Current state
        updates: Dictionary of fields to update
        
    Returns:
        Updated state
    """
    new_state = dict(state)  # Copy
    new_state.update(updates)  # Apply updates
    return new_state

def add_to_history(state: AgentState, node_name: str) -> AgentState:
    """
    Record that a node was visited.
    
    Args:
        state: Current state
        node_name: Name of the node being visited
        
    Returns:
        Updated state with node added to history
    """
    history = state.get("node_history", [])
    history.append(node_name)
    return update_state(state, {"node_history": history})

def add_correction_record(
    state: AgentState, 
    feedback: str, 
    attempt: int
) -> AgentState:
    """
    Record a correction attempt.
    
    Args:
        state: Current state
        feedback: What was wrong
        attempt: Attempt number
        
    Returns:
        Updated state with correction record
    """
    history = state.get("correction_history", [])
    history.append({
        "attempt": attempt,
        "feedback": feedback,
        "timestamp": datetime.now().isoformat()
    })
    return update_state(state, {
        "correction_history": history,
        "correction_attempts": attempt
    })

