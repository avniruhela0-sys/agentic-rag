def create_initial_state(question: str) -> AgentState:
    """
    Create a fresh state for a new question.
    
    Args:
        question: The user's question
        
    Returns:
        A new AgentState with default values
    """
    return AgentState(
        # Input
        question=question,
        
        # Planning (empty initially)
        sub_questions=[],
        
        # Retrieval (empty initially)
        retrieved_docs=[],
        
        # Generation (empty initially)
        draft_answer="",
        
        # Evaluation (default values)
        judge_score=0.0,
        judge_feedback="",
        judge_issue="none",
        
        # Correction (start at 0)
        correction_attempts=0,
        correction_history=[],
        
        # Final (empty initially)
        final_answer="",
        sources=[],
        
        # Metadata
        start_time=datetime.now().isoformat(),
        node_history=[]
    )

print("✅ create_initial_state() function defined!")

